// Writes one small entry per effect (js/entry/<pack>/<id>.js), so a page that uses one effect only bundles that one:
//   import { reveal } from '@brightkumedzro/reveal/elemental/fire';
// package.json maps '@brightkumedzro/reveal/<pack>/<id>' to these files with one pattern per pack.
// Run after adding an effect to a pack: node scripts/entries.mjs
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const PACKS = ['elemental', 'shinobi', 'paper'];

for (const pack of PACKS) {
  // the pack's effects, in order, from its index.js: `import fire from './fire.js';`
  const index = readFileSync(`${root}/js/${pack}/index.js`, 'utf8');
  const ids = [...index.matchAll(/^import (\w+) from '\.\/(\w+)\.js';/gm)].map((m) => m[2]);
  const dir = `${root}/js/entry/${pack}`;
  mkdirSync(dir, { recursive: true });
  for (const f of readdirSync(dir)) if (!ids.includes(f.replace(/\.js$/, ''))) rmSync(`${dir}/${f}`);
  for (const id of ids) {
    writeFileSync(`${dir}/${id}.js`, `/* @brightkumedzro/reveal/${pack}/${id}: just this one effect, for the smallest bundle (generated by scripts/entries.mjs).
     import { reveal } from '@brightkumedzro/reveal/${pack}/${id}';
     reveal('#hero', { from: '/sketch.png', to: '/final.png' });
   Same options as the full library; \`effect\` isn't needed. */
import { makeReveal, VERSION, gpu } from '../../reveal.js';
import ${id} from '../../${pack}/${id}.js';

export const effect = ${id};
export const reveal = makeReveal({ ${id} });
export { VERSION, gpu };
export default reveal;
`);
  }
  console.log(pack, ids.join(' '));
}

const pkg = JSON.parse(readFileSync(`${root}/package.json`, 'utf8'));
const ex = {};
for (const [k, v] of Object.entries(pkg.exports)) {
  if (k === './package.json') continue;
  ex[k] = v;
  if (PACKS.includes(k.slice(2))) ex[`${k}/*`] = `./js/entry/${k.slice(2)}/*.js`;
}
ex['./package.json'] = './package.json';
pkg.exports = ex;
writeFileSync(`${root}/package.json`, JSON.stringify(pkg, null, 2) + '\n');
console.log('package.json exports:', Object.keys(ex).join(' '));
